# -*- coding: utf-8 -*-
"""
Общие цветовые токены UI.

Раньше "фон блока" (_BLOCK_BG) был локальной константой в ui/sidebar.py,
а ui/fx_grid.py определял свой собственный, БЛИЗКИЙ, но не совпадающий
оттенок серого для фона плиток (_COLOR_IDLE_BG). Из-за этого плитки FX
визуально не сливались с фоном своего же контейнера — два соседних,
но чуть разных серых пятна. Прямой импорт из ui.sidebar в ui.fx_grid
невозможен (sidebar.py сам импортирует FXGrid — цикл), поэтому общие
токены вынесены в отдельный "листовой" модуль без зависимостей от
других ui/* модулей.

Один акцентный цвет — ACCENT_BLUE (тот же, что в ctk theme "blue" и
на кнопке "Пресеты стиля"). Раньше у "включённого" эффекта в FX-сетке
был ОТДЕЛЬНЫЙ акцент — бирюза (#26a69a), никак не связанный с общей
темой. ACCENT_BLUE_LIGHT — более светлый оттенок ТОГО ЖЕ синего для
состояния "включён, но не активен" — чтобы на плитках был один
акцентный цвет, а не три конкурирующих (синий + бирюза + сам разноцветный
глиф эффекта).
"""

# Фон "блочных" секций (header, FX-контейнер) — светлая/тёмная тема.
BLOCK_BG = ("#d0d0d0", "#333333")

# Фон элементов ВНУТРИ блока, которые должны сливаться с ним
# (например, плитки FX в состоянии покоя) — тот же тон, что BLOCK_BG.
BLOCK_ITEM_BG = BLOCK_BG

# Акцент "активен" (открыт справа) — совпадает с акцентом ctk theme "blue".
ACCENT_BLUE = "#1f538d"

# Акцент "включён, но сейчас не активен" — светлее того же синего,
# а не отдельный несвязанный оттенок (было "#26a69a", бирюза).
ACCENT_BLUE_LIGHT = "#5b9bd5"

# Наведение — на тон темнее/светлее BLOCK_ITEM_BG, не отдельная палитра.
HOVER_BG = ("#c2c2c2", "#454545")

# Нейтральная рамка для состояний "обычная"/"активная" (без enabled) —
# на тон заметнее фона плитки, но не цветная/акцентная. Акцентный цвет
# рамки (ACCENT_BLUE_LIGHT) зарезервирован строго за "включено".
BORDER_IDLE = ("#b5b5b5", "#4a4a4a")

# Единое скругление для "плиточных" кнопок — совпадает с обычными
# CTkButton приложения (было 4 у FX-плиток при ~6-8 у остальных кнопок).
TILE_CORNER_RADIUS = 8
